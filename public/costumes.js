/** Parsed costume for a 2- to 5-digit SSIC code, or null (sections). */
export function costumeFor(code) {
  const spec = /^\d{2,5}$/.test(code) ? DIVISION[code.slice(0, 2)] : null;
  if (!spec) return null;
  const [outfit, hat, prop, ...extras] = spec.split(/\s+/);
  const [name, colours = ""] = outfit.split("/");
  const o = OUTFITS[name];
  const fill = (s) => s.replace(/a/g, colours[0]).replace(/b/g, colours[1]);
  return {
    shirt: fill(o.shirt),
    pants: fill(o.pants),
    rows: o.rows.map(fill),
    hat: hat === "-" ? null : HATS[hat],
    prop: PROPS[prop],
    extras: new Set(extras),
  };
}
